from inspect import classify_class_attrs

# Função para calcular a média
def calcular_media(soma_notas, quantidade):
    if quantidade == 0:
        return None
    return soma_notas / quantidade

# Lista fixa com as 5 matérias
materias = ["Nota 1", "Nota 2", "Nota 3", "Nota 4", "Nota 5"]

# Variáveis para guardar os totais (substituem total_vendas e qtd_vendas)
soma_notas = 0.0
qtd_notas = 0

print("-- Boletim de Notas --")
print("Você tem cinco matérias para avaliar.")

while True:
    print("\n----- Sistema de Gestão de Notas -----")
    print("1 - Registrar nota de uma matéria")
    print("2 - Ver relatório do boletim")
    print("0 - Encerrar o programa")
    opcao = input("Escolha uma opção: ")

    if opcao == "0":
        print("Encerrando o sistema. Até logo!")
        break

    elif opcao == "1":
        # Verifica se já registrou o limite de 5 notas
        if qtd_notas >= 5:
            print("Todas as 5 matérias já foram cadastradas!")
        else:
            materia_atual = materias[qtd_notas]
            print(f"\nCadastrando: {materia_atual}")

            nota = float(input(f"Digite a nota (0 a 10): "))

            # Valida se a nota está no intervalo permitido
            if nota < 0 or nota > 10:
                print("Nota inválida! Use um valor entre 0 e 10.")
            else:
                soma_notas = soma_notas + nota
                qtd_notas = qtd_notas + 1
                print(f">> {materia_atual} registrada com sucesso: {nota:.2f}")

    elif opcao == "2":
        if qtd_notas == 0:
            print("\nNenhuma nota foi registrada ainda.")
        else:
            media = calcular_media(soma_notas, qtd_notas)

            print(f"\n--- RELATÓRIO PARCIAL/FINAL ---")
            print(f"Matérias cadastradas: {qtd_notas} de 5")
            print(f"Soma total das notas: {soma_notas:.2f}")
            print(f"Média atual         : {media:.2f}")

            # Avalia a situação se já cadastrou todas as 5
            if qtd_notas == 5:
                if media >= 7.0:
                    print("Situação final      : APROVADO")
                else:
                    print("Situação final      : REPROVADO")

    else:
        print("Opção Inválida. Tente de novo.")